// Guess device type from vendor name
function guessDeviceType(vendor: string | null): string {
  if (!vendor) return "other";
  const v = vendor.toLowerCase();
  if (
    v.includes("tp-link") ||
    v.includes("cisco") ||
    v.includes("mikrotik") ||
    v.includes("netgear") ||
    v.includes("d-link") ||
    v.includes("linksys") ||
    v.includes("belkin") ||
    v.includes("ubiquiti") ||
    v.includes("aruba") ||
    v.includes("fortinet") ||
    v.includes("sonicwall") ||
    v.includes("sophos") ||
    v.includes("huawei")
  )
    return "router";
  if (v.includes("apple")) return "mobile";
  if (
    v.includes("samsung") ||
    v.includes("xiaomi") ||
    v.includes("oppo") ||
    v.includes("vivo") ||
    v.includes("realme")
  )
    return "mobile";
  if (v.includes("dell") || v.includes("hewlett") || v.includes("hp"))
    return "pc";
  if (v.includes("intel") || v.includes("asus") || v.includes("lenovo"))
    return "pc";
  if (v.includes("raspberry")) return "server";
  if (v.includes("vmware") || v.includes("hyper-v") || v.includes("virtual"))
    return "server";
  if (v.includes("hikvision") || v.includes("dahua")) return "other";
  if (v.includes("synology")) return "server";
  if (
    v.includes("brother") ||
    v.includes("canon") ||
    v.includes("epson") ||
    v.includes("ricoh")
  )
    return "printer";
  return "other";
}

export async function POST(req: NextRequest) {
  try {
    const body = await req.json();
    const subnet = body.subnet; // e.g. "192.168.1"

    // Use local-devices to scan network
    let rawDevices;
    
    if (subnet) {
      // Scan specific subnet
      rawDevices = await localDevices({ address: `${subnet}.0` });
    } else {
      // Scan all local networks
      rawDevices = await localDevices();
    }

    // Transform to our format
    const discovered: DiscoveredDevice[] = rawDevices.map((device: any) => ({
      ipAddress: device.ip,
      macAddress: device.mac ? device.mac.toUpperCase() : null,
      vendor: device.name || (device.mac ? lookupVendor(device.mac.toUpperCase()) : null),
      status: "online" as const,
    }));

    // Filter by subnet if specified (additional filtering)
    const filtered = subnet
      ? discovered.filter((d) => d.ipAddress.startsWith(subnet + "."))
      : discovered;

    // Enrich with vendor/type info
    const enriched = filtered.map((d) => ({
      ...d,
      vendor: d.vendor,
      guessedType: guessDeviceType(d.vendor),
    }));

    // Step 3: Save/update discovered devices in database
    const { prisma } = await import("@/lib/db");
    
    for (const device of enriched) {
      const key = {
        ipAddress: device.ipAddress,
        macAddress: device.macAddress || "",
      };

      // Check if device exists
      const existing = await prisma.discoveredDevice.findUnique({
        where: {
          ipAddress_macAddress: key,
        },
      });

      if (existing) {
        // Update existing device
        await prisma.discoveredDevice.update({
          where: { id: existing.id },
          data: {
            lastSeenAt: new Date(),
            scanCount: { increment: 1 },
            status: "online",
            vendor: device.vendor || existing.vendor,
            guessedType: device.guessedType || existing.guessedType,
          },
        });
      } else {
        // Create new discovered device
        await prisma.discoveredDevice.create({
          data: {
            ipAddress: device.ipAddress,
            macAddress: device.macAddress,
            vendor: device.vendor,
            guessedType: device.guessedType,
            status: "online",
            scanCount: 1,
          },
        });
      }
    }

    return NextResponse.json({
      devices: enriched,
      total: enriched.length,
      subnet: subnet || "all",
      saved: true,
    });
  } catch (error) {
    console.error("Network scan error:", error);
    return NextResponse.json(
      { error: "ເກີດຂໍ້ຜິດພາດໃນການ scan ເຄືອຂ່າຍ" },
      { status: 500 }
    );
  }
}
